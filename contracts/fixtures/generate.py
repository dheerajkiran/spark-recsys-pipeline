"""Generate two isolated synthetic datasets over the eight bundled real clips.

Usage: python -m contracts.fixtures.generate --output data/platform-fixtures
Generated bytes are reproducible; existing non-identical output is never replaced.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import tempfile
import uuid
from datetime import timedelta
from pathlib import Path

from contracts.data import ContractError, DEFAULT_POLICY, isoformat, timestamp, validate_dataset, validate_media

CATALOG_PATH = Path(__file__).with_name("catalog.json")
SPLITS = {"train_start": "2026-10-01T00:00:00Z", "validation_start": "2026-10-08T00:00:00Z",
          "test_start": "2026-10-10T00:00:00Z", "test_end": "2026-10-12T00:00:00Z"}
WATERMARK = "2026-10-15T00:00:00Z"
ITEM_FIELDS = ["item_id", "published_at", "active", "topic", "duration_ms"]
EVENT_FIELDS = ["event_id", "event_type", "user_id", "item_id", "occurred_at", "impression_id",
                "request_id", "session_id", "watch_ms", "received_at"]
USER_FIELDS = ["user_id", "created_at"]


def _json(path, payload):
    path.write_text(json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")


def _csv(path, fields, rows):
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fields, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({key: "true" if value is True else "false" if value is False else value for key, value in row.items()})


def _inventory(path, rows):
    data = path.read_bytes()
    return {"name": path.name, "byte_length": len(data), "sha256": hashlib.sha256(data).hexdigest(), "row_count": rows}


def _project(directory, index, seed, impressions, catalog):
    directory.mkdir()
    rng = random.Random(seed + index * 1_000_003)
    media = catalog["items"]
    topics = sorted({item["topic"] for item in media})
    preferences = {f"user_{user:03d}": topics[(user + index) % len(topics)] for user in range(100)}
    users = [{"user_id": user, "created_at": "2026-01-01T00:00:00Z"} for user in preferences]
    items = [{"item_id": item["item_id"], "published_at": "2026-01-01T00:00:00Z", "active": True,
              "topic": item["topic"], "duration_ms": item["duration_ms"]} for item in media]
    start = timestamp(SPLITS["train_start"])
    duration = int((timestamp(SPLITS["test_end"]) - start).total_seconds())
    events = []
    for number in range(impressions):
        user = f"user_{number % 100:03d}"
        item = media[rng.randrange(len(media))]
        at = start + timedelta(seconds=(duration * number) // impressions)
        common = {"user_id": user, "item_id": item["item_id"], "impression_id": f"imp_{number:06d}",
                  "request_id": f"rec_{number:06d}", "session_id": f"session_{number // 20:05d}"}
        events.append({**common, "event_id": f"evt_imp_{number:06d}", "event_type": "impression",
                       "occurred_at": isoformat(at), "received_at": isoformat(at + timedelta(seconds=1))})
        probability = 0.72 if item["topic"] == preferences[user] else 0.12
        if rng.random() < probability:
            click_at = at + timedelta(seconds=rng.randint(2, 120))
            events.append({**common, "event_id": f"evt_click_{number:06d}", "event_type": "click",
                           "occurred_at": isoformat(click_at), "received_at": isoformat(click_at + timedelta(seconds=rng.randint(0, 20)))})
        if rng.random() < 0.35:
            watch_ms = rng.randint(1, item["duration_ms"])
            watch_at = at + timedelta(seconds=(watch_ms + 999) // 1000)
            events.append({**common, "event_id": f"evt_watch_{number:06d}", "event_type": "watch", "watch_ms": watch_ms,
                           "occurred_at": isoformat(watch_at), "received_at": isoformat(watch_at + timedelta(seconds=1))})
    events.sort(key=lambda event: (timestamp(event["occurred_at"]), event["event_id"]))
    _csv(directory / "items.csv", ITEM_FIELDS, items)
    _csv(directory / "events.csv", EVENT_FIELDS, events)
    _csv(directory / "users.csv", USER_FIELDS, users)
    _json(directory / "media.json", catalog)
    identity = hashlib.sha256(json.dumps(catalog, sort_keys=True).encode()).hexdigest()
    manifest = {"schema_version": "recommendation-v1",
                "project_id": "prj_" + uuid.uuid5(uuid.NAMESPACE_URL, f"loop.phase71.project.{index}").hex,
                "dataset_id": "dts_" + uuid.uuid5(uuid.NAMESPACE_URL, f"loop.phase71.dataset.{index}.{seed}.{impressions}.{identity}").hex,
                "provenance": {"kind": "synthetic", "generator": "phase71-fixture-v1", "seed": seed,
                               "note": "Synthetic users, exposures, clicks, watches, receipt times, and item publication times over eight credited bundled clips. No real-user relevance or historical arrival replay claim."},
                "availability_mode": "recorded_arrival", "label_policy": DEFAULT_POLICY,
                "split_cutoffs": SPLITS, "extraction_watermark": WATERMARK,
                "timestamp_range": {"start": events[0]["occurred_at"], "end": events[-1]["occurred_at"]},
                "files": [_inventory(directory / "items.csv", len(items)), _inventory(directory / "events.csv", len(events)),
                          _inventory(directory / "users.csv", len(users))],
                "auxiliary_files": [_inventory(directory / "media.json", len(media))]}
    _json(directory / "manifest.json", manifest)
    return validate_dataset(directory)


def _tree_digests(directory):
    if directory.is_symlink() or not directory.is_dir():
        raise ContractError("output_exists", "Existing output is not a regular fixture directory.")
    result = {}
    for path in directory.rglob("*"):
        if path.is_symlink():
            raise ContractError("output_exists", "Existing output contains a symlink.")
        if path.is_file():
            result[path.relative_to(directory).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return result


def generate(output, *, seed=7101, impressions=10_000):
    if type(seed) is not int or not 0 <= seed <= 2_147_483_647:
        raise ContractError("invalid_seed", "Seed must be an integer from 0 through 2147483647.")
    if type(impressions) is not int or not 1 <= impressions <= 30_000:
        raise ContractError("invalid_impressions", "Impression count must be from 1 through 30000 per project.")
    output = Path(output).absolute()
    if output.is_symlink():
        raise ContractError("output_exists", "Output must not be a symlink.")
    output.parent.mkdir(parents=True, exist_ok=True)
    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    validate_media(catalog, check_assets=True)
    with tempfile.TemporaryDirectory(prefix=".phase71-fixture-", dir=output.parent) as temporary:
        staged = Path(temporary) / "datasets"
        staged.mkdir()
        reports = [_project(staged / f"project-{index + 1}", index, seed, impressions, catalog) for index in range(2)]
        if output.exists():
            if _tree_digests(output) != _tree_digests(staged):
                raise ContractError("output_exists", "Existing output differs; choose a new output directory.")
        else:
            staged.rename(output)
    return {"generator": "phase71-fixture-v1", "seed": seed, "projects": reports}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=7101)
    parser.add_argument("--impressions", type=int, default=10_000, help="Impressions per project (1–30000).")
    args = parser.parse_args()
    try:
        report = generate(args.output, seed=args.seed, impressions=args.impressions)
    except ContractError as exc:
        print(json.dumps({"error": exc.as_dict()}, sort_keys=True))
        raise SystemExit(1) from exc
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
